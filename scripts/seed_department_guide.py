async def main():
    async with async_session() as session:
        count = 0
        for dept, cat, disease, symptoms, keywords in GUIDE_DATA:
            result = await session.execute(
                select(DepartmentGuide).where(
                    DepartmentGuide.department == dept,
                    DepartmentGuide.disease == disease,
                )
            )
            if not result.scalar_one_or_none():
                session.add(DepartmentGuide(
                    department=dept,
                    category=cat,
                    disease=disease,
                    symptoms=symptoms,
                    keywords=keywords,
                ))
                count += 1
        await session.commit()
    print(f"新增 {count} 筆就醫指南（共 {len(GUIDE_DATA)} 筆）")


if __name__ == "__main__":
    asyncio.run(main())
